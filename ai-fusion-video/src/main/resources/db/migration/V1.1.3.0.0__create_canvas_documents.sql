CREATE TABLE `afv_canvas_value_snapshot` (
  `id` char(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '固定结果快照标识',
  `canvas_id` char(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '快照所属画布标识',
  `node_id` char(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '副本中对应的来源节点标识',
  `port_id` varchar(96) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '固定的输出端口',
  `schema_version` int NOT NULL COMMENT '快照协议版本',
  `value_json` json NOT NULL COMMENT '经权限校验冻结的完整类型化结果，不含访问票据或密钥',
  `source_canvas_id` char(36) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL COMMENT '原始画布标识，模板导入时为空',
  `source_node_run_id` char(36) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL COMMENT '原始节点运行标识',
  `source_output_id` varchar(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '原始结果标识',
  `source_snapshot_id` char(36) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL COMMENT '复制前的固定结果快照标识',
  `created_by` bigint NOT NULL COMMENT '创建快照的用户标识',
  `created_at` datetime(6) NOT NULL COMMENT '创建时间',
  `source_kind` varchar(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'CANVAS' COMMENT '固定结果来源：画布复制或模板导入',
  `template_hash` char(64) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL COMMENT '导入模板的内容摘要',
  PRIMARY KEY (`id`),
  KEY `idx_canvas_value_snapshot_canvas` (`canvas_id`,`node_id`),
  CONSTRAINT `fk_canvas_value_snapshot_canvas` FOREIGN KEY (`canvas_id`) REFERENCES `afv_canvas` (`id`),
  CONSTRAINT `ck_canvas_value_snapshot_schema` CHECK (((`schema_version` = 1) and (json_type(`value_json`) = _utf8mb4'OBJECT'))),
  CONSTRAINT `ck_canvas_value_snapshot_source` CHECK ((((`source_kind` = _utf8mb4'CANVAS') and (`source_canvas_id` is not null) and (`template_hash` is null)) or ((`source_kind` = _utf8mb4'TEMPLATE') and (`source_canvas_id` is null) and (`source_node_run_id` is null) and (`source_snapshot_id` is null) and (`template_hash` is not null) and regexp_like(`template_hash`,_utf8mb4'^[0-9a-f]{64}$'))))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='复制画布时保留的受保护固定结果';
