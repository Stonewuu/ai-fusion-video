-- 创建画布文档、操作历史和固定结果，并建立跨画布关系约束。

CREATE TABLE `afv_canvas` (
  `id` char(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '画布唯一标识',
  `title` varchar(200) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '画布名称',
  `project_id` bigint DEFAULT NULL COMMENT '关联项目编号',
  `owner_type` tinyint NOT NULL COMMENT '所有者类型：1个人，2团队',
  `owner_id` bigint NOT NULL COMMENT '所有者编号',
  `created_by` bigint NOT NULL COMMENT '创建用户编号',
  `schema_version` int NOT NULL DEFAULT '1' COMMENT '画布协议版本',
  `revision` bigint NOT NULL DEFAULT '0' COMMENT '已提交文档版本',
  `next_event_sequence` bigint NOT NULL DEFAULT '1' COMMENT '下一条提交事件序号',
  `archived` tinyint(1) NOT NULL DEFAULT '0' COMMENT '是否已归档',
  `create_time` datetime(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '创建时间',
  `update_time` datetime(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '更新时间',
  PRIMARY KEY (`id`),
  KEY `idx_canvas_owner` (`owner_type`,`owner_id`,`archived`,`update_time`),
  KEY `idx_canvas_project` (`project_id`,`archived`,`update_time`),
  KEY `idx_canvas_creator` (`created_by`,`archived`,`update_time`),
  CONSTRAINT `ck_canvas_owner` CHECK (((`owner_type` in (1,2)) and (`owner_id` > 0) and (`created_by` > 0))),
  CONSTRAINT `ck_canvas_version` CHECK (((`schema_version` = 1) and (`revision` >= 0) and (`next_event_sequence` > 0)))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='创作画布';

CREATE TABLE `afv_canvas_member` (
  `canvas_id` char(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '画布标识',
  `user_id` bigint NOT NULL COMMENT '成员用户编号',
  `can_edit` tinyint(1) NOT NULL DEFAULT '0' COMMENT '是否可编辑画布',
  `can_execute` tinyint(1) NOT NULL DEFAULT '0' COMMENT '是否可执行创作任务',
  `can_manage` tinyint(1) NOT NULL DEFAULT '0' COMMENT '是否可管理共享与归档',
  `granted_by` bigint NOT NULL COMMENT '授权用户编号',
  `create_time` datetime(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '授权时间',
  `update_time` datetime(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '更新时间',
  PRIMARY KEY (`canvas_id`,`user_id`),
  KEY `idx_canvas_member_user` (`user_id`,`canvas_id`),
  CONSTRAINT `fk_canvas_member_document` FOREIGN KEY (`canvas_id`) REFERENCES `afv_canvas` (`id`),
  CONSTRAINT `ck_canvas_member_user` CHECK (((`user_id` > 0) and (`granted_by` > 0)))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='画布共享成员权限';

CREATE TABLE `afv_canvas_node` (
  `id` char(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '节点唯一标识',
  `canvas_id` char(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '所属画布标识',
  `kind` varchar(48) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '节点类型',
  `schema_version` int NOT NULL DEFAULT '1' COMMENT '节点协议版本',
  `title` varchar(200) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '节点名称',
  `x` double NOT NULL COMMENT '画布横坐标',
  `y` double NOT NULL COMMENT '画布纵坐标',
  `width` double DEFAULT NULL COMMENT '指定展示宽度',
  `height` double DEFAULT NULL COMMENT '指定展示高度',
  `parent_id` char(36) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL COMMENT '父分组节点标识',
  `locked` tinyint(1) NOT NULL DEFAULT '0' COMMENT '是否锁定位置',
  `collapsed` tinyint(1) NOT NULL DEFAULT '0' COMMENT '是否折叠',
  `config_json` json NOT NULL COMMENT '经过协议校验的节点配置',
  `resource_type` varchar(32) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL COMMENT '绑定的业务对象类型',
  `resource_id` bigint DEFAULT NULL COMMENT '绑定的业务对象编号',
  `resource_version` bigint DEFAULT NULL COMMENT '最近确认的业务对象版本',
  `config_version` bigint NOT NULL DEFAULT '0' COMMENT '配置与绑定版本',
  `layout_version` bigint NOT NULL DEFAULT '0' COMMENT '空间布局版本',
  `deleted` tinyint(1) NOT NULL DEFAULT '0' COMMENT '是否已删除视图',
  `create_time` datetime(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '创建时间',
  `update_time` datetime(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '更新时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_canvas_node_document` (`canvas_id`,`id`),
  KEY `idx_canvas_node_document` (`canvas_id`,`deleted`,`parent_id`),
  KEY `idx_canvas_node_resource` (`resource_type`,`resource_id`,`deleted`,`canvas_id`),
  KEY `fk_canvas_node_parent` (`canvas_id`,`parent_id`),
  KEY `idx_canvas_node_read_order` (`canvas_id`,`deleted`,`create_time`,`id`) COMMENT '按画布顺序读取节点，避免大配置参与文件排序',
  CONSTRAINT `fk_canvas_node_document` FOREIGN KEY (`canvas_id`) REFERENCES `afv_canvas` (`id`),
  CONSTRAINT `fk_canvas_node_parent` FOREIGN KEY (`canvas_id`, `parent_id`) REFERENCES `afv_canvas_node` (`canvas_id`, `id`),
  CONSTRAINT `ck_canvas_node_config` CHECK ((json_type(`config_json`) = _utf8mb4'OBJECT')),
  CONSTRAINT `ck_canvas_node_reference` CHECK ((((`resource_type` is null) and (`resource_id` is null) and (`resource_version` is null)) or ((`resource_type` is not null) and (`resource_id` > 0) and (`resource_version` >= 0) and (`resource_id` is not null) and (`resource_version` is not null)))),
  CONSTRAINT `ck_canvas_node_size` CHECK ((((`width` is null) or (`width` > 0)) and ((`height` is null) or (`height` > 0)))),
  CONSTRAINT `ck_canvas_node_version` CHECK (((`schema_version` = 1) and (`config_version` >= 0) and (`layout_version` >= 0)))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='画布节点与业务引用';

CREATE TABLE `afv_canvas_edge` (
  `id` char(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '连线唯一标识',
  `canvas_id` char(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '所属画布标识',
  `kind` varchar(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '关系类型：执行、业务引用或注释',
  `source_node_id` char(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '来源节点标识',
  `source_port` varchar(64) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL COMMENT '来源输出端口',
  `target_node_id` char(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '目标节点标识',
  `target_port` varchar(64) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL COMMENT '目标输入端口',
  `input_index` int DEFAULT NULL COMMENT '目标端口中的显式输入顺序',
  `output_json` json DEFAULT NULL COMMENT '固定的运行与输出资源引用',
  `version` bigint NOT NULL DEFAULT '0' COMMENT '连线版本',
  `deleted` tinyint(1) NOT NULL DEFAULT '0' COMMENT '是否已删除连线',
  `active_target_node_id` char(36) CHARACTER SET ascii COLLATE ascii_bin GENERATED ALWAYS AS (if((`deleted` = false),`target_node_id`,NULL)) STORED COMMENT '用于约束有效输入位置的目标节点',
  `create_time` datetime(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '创建时间',
  `update_time` datetime(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '更新时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_canvas_edge_input` (`canvas_id`,`active_target_node_id`,`target_port`,`input_index`),
  KEY `idx_canvas_edge_document` (`canvas_id`,`deleted`),
  KEY `idx_canvas_edge_source` (`canvas_id`,`source_node_id`),
  KEY `idx_canvas_edge_target` (`canvas_id`,`target_node_id`),
  KEY `idx_canvas_edge_read_order` (`canvas_id`,`deleted`,`create_time`,`id`) COMMENT '按画布顺序读取连线，避免大输出引用参与文件排序',
  CONSTRAINT `fk_canvas_edge_source` FOREIGN KEY (`canvas_id`, `source_node_id`) REFERENCES `afv_canvas_node` (`canvas_id`, `id`),
  CONSTRAINT `fk_canvas_edge_target` FOREIGN KEY (`canvas_id`, `target_node_id`) REFERENCES `afv_canvas_node` (`canvas_id`, `id`),
  CONSTRAINT `ck_canvas_edge_binding` CHECK ((((`kind` = _ascii'execution') and (`source_port` is not null) and (`target_port` is not null) and (`input_index` is not null) and (`input_index` >= 0)) or ((`kind` in (_ascii'reference',_ascii'annotation')) and (`source_port` is null) and (`target_port` is null) and (`input_index` is null) and (`output_json` is null)))),
  CONSTRAINT `ck_canvas_edge_kind` CHECK ((`kind` in (_ascii'execution',_ascii'reference',_ascii'annotation'))),
  CONSTRAINT `ck_canvas_edge_version` CHECK ((`version` >= 0))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='画布关系与有类型的执行连线';

CREATE TABLE `afv_canvas_operation` (
  `id` char(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '命令提交标识',
  `canvas_id` char(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '画布标识',
  `actor_user_id` bigint NOT NULL COMMENT '经过认证的操作用户编号',
  `request_id` varchar(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '请求幂等标识',
  `request_hash` char(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '请求规范化摘要',
  `origin` varchar(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '操作来源',
  `agent_run_id` varchar(64) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL COMMENT '关联智能体运行标识',
  `tool_call_id` varchar(128) CHARACTER SET ascii COLLATE ascii_bin DEFAULT NULL COMMENT '关联工具调用标识',
  `committed_revision` bigint NOT NULL COMMENT '提交后的文档版本',
  `request_json` json NOT NULL COMMENT '已验证的命令内容',
  `result_json` json NOT NULL COMMENT '幂等提交回执',
  `undo_json` json DEFAULT NULL COMMENT '有条件撤销所需的变更前值',
  `create_time` datetime(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '提交时间',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_canvas_operation_document` (`canvas_id`,`id`),
  UNIQUE KEY `uk_canvas_operation_request` (`canvas_id`,`actor_user_id`,`request_id`),
  UNIQUE KEY `uk_canvas_operation_revision` (`canvas_id`,`committed_revision`),
  KEY `idx_canvas_operation_agent` (`agent_run_id`,`tool_call_id`),
  CONSTRAINT `fk_canvas_operation_document` FOREIGN KEY (`canvas_id`) REFERENCES `afv_canvas` (`id`),
  CONSTRAINT `ck_canvas_operation_actor` CHECK (((`actor_user_id` > 0) and (`committed_revision` > 0))),
  CONSTRAINT `ck_canvas_operation_json` CHECK (((json_type(`request_json`) = _utf8mb4'OBJECT') and (json_type(`result_json`) = _utf8mb4'OBJECT'))),
  CONSTRAINT `ck_canvas_operation_origin` CHECK ((`origin` in (_utf8mb4'user',_utf8mb4'agent',_utf8mb4'system')))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='画布命令幂等回执与操作审计';

CREATE TABLE `afv_canvas_event` (
